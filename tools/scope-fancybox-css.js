/*
 * Writes a copy of Fancybox's stylesheet that only applies to this plugin's
 * own lightbox (the `.vidgalblkFancyBox` main class). The stock file styles
 * every `.fancybox__container` on the page -- including another plugin's
 * lightbox built on a different Fancybox version, which it left hidden.
 * Run again after upgrading @fancyapps/ui.
 */
const fs = require("fs");
const path = require("path");
const postcss = require("postcss");

const SCOPE = ".vidgalblkFancyBox";
const src = path.join(__dirname, "../node_modules/@fancyapps/ui/dist/fancybox/fancybox.css");
const out = path.join(__dirname, "../src/blocks/video-gallery-block/fancybox-scoped.css");

const root = postcss.parse(fs.readFileSync(src, "utf8"));

const frames = new Set();
root.walkAtRules(/keyframes$/, (a) => frames.add(a.params));
const rename = (v) => v.replace(/[A-Za-z0-9_-]+/g, (w) => (frames.has(w) ? `vgb-${w}` : w));

root.walkAtRules(/keyframes$/, (a) => { a.params = `vgb-${a.params}`; });
root.walkDecls(/^animation(-name)?$/, (d) => { d.value = rename(d.value); });

const scope = (sel) => {
  sel = sel.trim();
  if (sel === ":root") return SCOPE;
  if (sel.startsWith("html.with-fancybox")) return sel;
  // Fancybox 6 wraps the container in a <dialog>, so scope the dialog by what it holds.
  if (sel.startsWith(".fancybox__dialog")) return `.fancybox__dialog:has(.fancybox__container${SCOPE})` + sel.slice(".fancybox__dialog".length);
  if (sel.startsWith(".fancybox__container")) return `.fancybox__container${SCOPE}` + sel.slice(".fancybox__container".length);
  const out = [`${SCOPE} ${sel}`];
  // The container itself carries show/hide and state classes.
  if (sel.startsWith(".")) out.push(`${SCOPE}${sel}`);
  return out.join(", ");
};

root.walkRules((r) => {
  if (r.parent && r.parent.type === "atrule" && /keyframes$/.test(r.parent.name)) return;
  r.selector = r.selectors.map(scope).join(", ");
});

fs.writeFileSync(out, "/* Generated by tools/scope-fancybox-css.js -- do not edit. */\n" + root.toString());
console.log("wrote", out);
